# ------------------------------------------------------------------------------------------ модель
@dataclass(frozen=True)
class Skill:
    key: str
    title: str

    def as_dict(self) -> dict[str, str]:
        return {"key": self.key, "title": self.title}


@dataclass(frozen=True)
class Topic:
    topic_id: str
    subject: str
    subject_title: str
    grade: int
    title: str
    keywords: tuple[str, ...]
    default_mechanic: str
    skills: tuple[Skill, ...]
    fgos_ref: str
    order: int
    paragraph_numbers: tuple[int, ...] = field(default=())

    def as_dict(self) -> dict[str, Any]:
        return {"topic_id": self.topic_id, "subject": self.subject, "subject_title": self.subject_title,
                "grade": self.grade, "title": self.title, "fgos_ref": self.fgos_ref,
                "default_mechanic": self.default_mechanic, "skills": [s.as_dict() for s in self.skills],
                "paragraph_numbers": list(self.paragraph_numbers)}


_TRANSLIT = str.maketrans({"а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "e", "ж": "zh", "з": "z",
                           "и": "i", "й": "y", "к": "k", "л": "l", "м": "m", "н": "n", "о": "o", "п": "p", "р": "r",
                           "с": "s", "т": "t", "у": "u", "ф": "f", "х": "h", "ц": "c", "ч": "ch", "ш": "sh", "щ": "sch",
                           "ъ": "", "ы": "y", "ь": "", "э": "e", "ю": "yu", "я": "ya"})


def slug(text: str, limit: int = 40) -> str:
    value = unicodedata.normalize("NFC", text).lower().translate(_TRANSLIT)
    value = re.sub(r"[^a-z0-9]+", "-", value).strip("-")
    return value[:limit].rstrip("-") or "x"


def _level(grade: int) -> str:
    return "НОО" if grade < 5 else ("ООО" if grade <= 9 else "СОО")


@lru_cache(maxsize=1)
def _build() -> tuple[Topic, ...]:
    topics: list[Topic] = []
    subject = ""
    counters: dict[tuple[str, int], int] = {}
    seen: set[str] = set()
    for raw in _TOPICS.strip().splitlines():
        line = raw.strip()
        if not line:
            continue
        if line.startswith("## "):
            subject = line[3:].strip()
            if subject not in SUBJECTS:
                raise ValueError(f"curriculum: неизвестный предмет {subject}")
            continue
        parts = [p.strip() for p in line.split("|")]
        if len(parts) != 5:
            raise ValueError(f"curriculum: строка должна иметь 5 полей: {line}")
        grade = int(parts[0])
        title, keywords, mechanic, skills_raw = parts[1], parts[2], parts[3], parts[4]
        meta = SUBJECTS[subject]
        if grade not in meta["grades"]:
            raise ValueError(f"curriculum: {subject} не изучается в {grade} классе")
        if mechanic not in MECHANICS:
            raise ValueError(f"curriculum: неизвестная механика {mechanic}")
        index = counters.get((subject, grade), 0) + 1
        counters[(subject, grade)] = index
        topic_id = f"{subject}-{grade}-{slug(title)}"
        if topic_id in seen:
            raise ValueError(f"curriculum: повтор темы {topic_id}")
        seen.add(topic_id)
        names = [s.strip() for s in skills_raw.split(";") if s.strip()] or list(meta["default_skills"])
        skills = tuple(Skill(f"{topic_id}:{slug(n, 32)}", n) for n in names)
        paragraphs = tuple(sorted(p for toc in TEXTBOOK_TOCS if toc["subject"] == subject and toc["grade"] == grade
                                  for p, t in toc["paragraphs"].items() if t == title))
        topics.append(Topic(topic_id=topic_id, subject=subject, subject_title=meta["title"], grade=grade, title=title,
                            keywords=tuple(k.strip().lower() for k in keywords.split(",") if k.strip()),
                            default_mechanic=mechanic, skills=skills,
                            fgos_ref=f"ФГОС {_level(grade)} · ФОП · {meta['title']} · {grade} кл. · раздел {index}",
                            order=index, paragraph_numbers=paragraphs))
    return tuple(topics)


def all_topics() -> tuple[Topic, ...]:
    return _build()


@lru_cache(maxsize=1)
def _by_id() -> dict[str, Topic]:
    return {t.topic_id: t for t in _build()}


def topic(topic_id: str) -> Topic | None:
    return _by_id().get(topic_id)


def normalize_subject(raw: str | None) -> str | None:
    """«Алгебра», «алгебра», «algebra», «Алгебра и начала анализа» → ``algebra``; неизвестное → None."""
    value = unicodedata.normalize("NFC", (raw or "")).strip().lower().replace("ё", "е")
    if not value:
        return None
    if value in SUBJECTS:
        return value
    for key, meta in SUBJECTS.items():
        names = [meta["title"].lower().replace("ё", "е"), *meta["aliases"]]
        if value in names:
            return key
    for key, meta in SUBJECTS.items():
        if any(value.startswith(a) for a in meta["aliases"] if len(a) >= 4):
            return key
    return None


def topics_for(subject: str, grade: int) -> list[Topic]:
    key = normalize_subject(subject) or subject
    return [t for t in _build() if t.subject == key and t.grade == grade]


def coverage() -> dict[str, list[int]]:
    """Предмет → классы, для которых в реестре есть темы (тест 5–11 проверяет полноту)."""
    out: dict[str, set[int]] = {}
    for t in _build():
        out.setdefault(t.subject, set()).add(t.grade)
    return {k: sorted(v) for k, v in out.items()}


# ---------------------------------------------------------------------- сопоставление ДЗ с темой
_PARAGRAPH = re.compile(r"§\s*(\d{1,3})|(?:параграф|пар\.|п\.)\s*(\d{1,3})", re.I)


def paragraph_of(text: str) -> int | None:
    match = _PARAGRAPH.search(text or "")
    if not match:
        return None
    return int(match.group(1) or match.group(2))


def _norm(text: str) -> str:
    return re.sub(r"\s+", " ", unicodedata.normalize("NFC", text or "").lower().replace("ё", "е"))


def _keyword_hits(topic_: Topic, text: str) -> int:
    hits = 0
    for keyword in topic_.keywords:
        kw = keyword.replace("ё", "е")
        if len(kw) >= 3 and kw in text:
            hits += 2 if " " in kw else 1
    if _norm(topic_.title) in text:
        hits += 3
    return hits


def verified_tocs(subject: str, grade: int) -> list[dict[str, Any]]:
    return [toc for toc in TEXTBOOK_TOCS if toc["subject"] == subject and toc["grade"] == grade and toc["verified"] is True]


PARAGRAPH_AUTO_MAX = 50       # v3.2 (решение PO): § 1..50 сопоставляются с темой автоматически


def textbook_tocs(subject: str, grade: int) -> list[dict[str, Any]]:
    return [toc for toc in TEXTBOOK_TOCS if toc["subject"] == subject and toc["grade"] == grade]


def program_order_topic(candidates: list[Topic], paragraph: int) -> Topic:
    """§ N → тема по порядку изучения: § 1..50 равномерно раскладываются по темам программы класса."""
    idx = min(len(candidates) - 1, (paragraph - 1) * len(candidates) // PARAGRAPH_AUTO_MAX)
    return candidates[idx]


def topic_label(paragraph: int | None, title: str) -> str:
    return f"Тема по программе ФГОС (§ {paragraph}): {title}" if paragraph else f"Тема по программе ФГОС: {title}"


def resolve_sgo_homework_topic(grade: int, subject: str, raw_hw_text: str, textbook_id: str | None = None) -> dict[str, Any]:
    """ДЗ из СГО («§ 12, № 245») → тема реестра.

    Порядок: тема названа в тексте (``keywords``) → сверенное оглавление (``verified_paragraph``) → несверенное
    оглавление учебника (``textbook_toc``) → порядок программы ФГОС для § 1..50 (``program_order``).
    v3.2 · решение PO заменяет правило Zero Hallucination № 7 для параграфов: стандартные номера § 1..50 сопоставляются
    автоматически (``needs_topic_clarification: False``), но экран всегда показывает, откуда взята тема
    («Тема по программе ФГОС (§ N): …») и даёт кнопку «Выбрать другую тему» (``options``). § > 50, неизвестный предмет
    или задание без темы и параграфа — честный запрос уточнения.

    Возвращает: ``topic`` (dict|None), ``needs_topic_clarification``, ``match``, ``paragraph``, ``label``, ``reason``,
    ``options`` — темы этого класса и предмета для выбора другой темы.
    """
    key = normalize_subject(subject)
    paragraph = paragraph_of(raw_hw_text)
    base: dict[str, Any] = {"subject": key, "grade": grade, "paragraph": paragraph, "topic": None,
                            "needs_topic_clarification": True, "match": "none", "options": [], "reason": "", "label": None}
    if key is None:
        base["reason"] = "Предмет не найден в программе 5–11 классов"
        return base
    if grade not in SUBJECTS[key]["grades"]:
        base["reason"] = f"{SUBJECTS[key]['title']} в {grade} классе по программе не изучается"
        return base
    candidates = topics_for(key, grade)
    base["options"] = [{"topic_id": t.topic_id, "title": t.title} for t in candidates]
    text = _norm(raw_hw_text)
    scored = sorted(((t, _keyword_hits(t, text)) for t in candidates), key=lambda x: -x[1])
    if scored and scored[0][1] > 0 and (len(scored) == 1 or scored[0][1] > scored[1][1]):
        best = scored[0][0]
        return {**base, "topic": best.as_dict(), "needs_topic_clarification": False, "match": "keywords",
                "label": topic_label(paragraph, best.title), "reason": "Тема названа в тексте задания"}
    if paragraph is not None and 1 <= paragraph <= PARAGRAPH_AUTO_MAX and candidates:
        for verified in (True, False):
            tocs = [toc for toc in textbook_tocs(key, grade) if toc["verified"] is verified]
            if textbook_id:
                tocs = [toc for toc in tocs if toc["id"] == textbook_id]
            if len(tocs) != 1:
                continue
            title = tocs[0]["paragraphs"].get(paragraph)
            found = next((t for t in candidates if t.title == title), None)
            if found is None:
                continue
            if verified:
                reason = f"§ {paragraph} по сверенному оглавлению учебника"
            else:
                reason = f"§ {paragraph} по оглавлению учебника «{tocs[0]['title']}» (не сверено с печатным изданием)"
            return {**base, "topic": found.as_dict(), "needs_topic_clarification": False,
                    "match": "verified_paragraph" if verified else "textbook_toc", "textbook": tocs[0]["title"],
                    "label": topic_label(paragraph, found.title), "reason": reason}
        found = program_order_topic(candidates, paragraph)
        return {**base, "topic": found.as_dict(), "needs_topic_clarification": False, "match": "program_order",
                "label": topic_label(paragraph, found.title),
                "reason": f"§ {paragraph} — по порядку изучения тем в программе {grade} класса. Если на уроке была другая тема, выбери её"}
    if paragraph is not None:
        base["reason"] = (f"В дневнике указан § {paragraph} — такого номера нет в обычной нумерации учебника. "
                          f"Выбери тему урока из программы {grade} класса или прикрепи фото страницы учебника")
        return base
    base["reason"] = f"Тема не названа. Выбери тему урока из программы {grade} класса или прикрепи фото страницы"
    return base
