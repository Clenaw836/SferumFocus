@dataclass
class ScrubResult:
    text: str
    counts: dict[str, int] = field(default_factory=dict)

    @property
    def total(self) -> int:
        return sum(self.counts.values())


def _replace(tag: str, pattern: re.Pattern[str], text: str, counts: dict[str, int]) -> str:
    def sub(match: re.Match[str]) -> str:
        found = match.group(0)
        if tag == PARTICIPANT:
            words = found.split()
            if any(re.sub(r"[^а-яё-]", "", w.lower()) in _PUBLIC_FIGURES for w in words):
                return found
            if len(words) == 2 and words[1] in _NOT_SURNAME:
                # «Саша Привет»: маскируем только имя, если оно однозначное.
                head = words[0]
                if head.lower() in _AMBIGUOUS:
                    return found
                counts[tag] = counts.get(tag, 0) + 1
                return f"{tag} {words[1]}"
        counts[tag] = counts.get(tag, 0) + 1
        return tag
    return pattern.sub(sub, text)


_PUBLIC_RE = re.compile(
    rf"(?:{_ANY_NAME_RE}\s+)?(?:{_INITIAL}{_INITIAL2})?(?:" + "|".join(sorted((re.escape(_cap(n)) for n in _PUBLIC_FIGURES), key=len, reverse=True))
    + rf")(?:а|у|ым|ом|е|ой|ого|ому|им|ой)?{_E}"
    + rf"|{_ANY_NAME_RE}\s+(?:Первый|Первого|Второй|Второго|Великий|Великого|Грозный|Грозного|Невский|Невского|Донской|Донского|I|II|III)(?![\w])")


def _protect(value: str) -> tuple[str, list[str]]:
    kept: list[str] = []

    def keep(match: re.Match[str]) -> str:
        kept.append(match.group(0))
        return f"\x00{len(kept) - 1}\x00"
    return _PUBLIC_RE.sub(keep, value), kept


def scrub(text: str | None) -> ScrubResult:
    """Маскирует ПДн и возвращает текст + число замен по меткам (для журнала — без самого текста)."""
    value = unicodedata.normalize("NFC", text or "").replace("\x00", "")
    value, kept = _protect(value)
    counts: dict[str, int] = {}
    for tag, pattern in _RULES:
        value = _replace(tag, pattern, value, counts)
    value = re.sub("\x00(\\d+)\x00", lambda m: kept[int(m.group(1))], value)
    # Две метки подряд («[УЧАСТНИК] [УЧАСТНИК]») — это одно ФИО, разбитое правилами.
    value = re.sub(r"(\[УЧАСТНИК\])(?:\s+\[УЧАСТНИК\])+", r"\1", value)
    return ScrubResult(value, counts)


def scrub_pii(text: str | None) -> str:
    """Публичный контракт SEC-01: текст → текст с метками [УЧАСТНИК]/[ТЕЛЕФОН]/[КОНТАКТ]/[ДОКУМЕНТ]."""
    return scrub(text).text


def short_alias(raw: str | None, limit: int = 20) -> str:
    """Гостевой PIN-блиц: «Иванов Иван Иванович» → «Иван И.»; «Парта 3» остаётся; не длиннее ``limit``.

    Правило: из трёх слов (ФИО) берём имя (второе слово) и первую букву фамилии; из двух — первое слово и
    инициал второго; цифры разрешены только в форме «Парта N». Всё, что не похоже на имя, — «Участник».
    """
    value = re.sub(r"<[^>]*>", " ", unicodedata.normalize("NFC", raw or ""))
    value = re.sub(r"\s+", " ", value).strip()
    value = re.sub(r"[^0-9A-Za-zА-Яа-яЁё .\-]", "", value).strip()
    if not value:
        return "Участник"
    desk = re.fullmatch(r"(?i)парта\s*№?\s*(\d{1,2})", value)
    if desk:
        return f"Парта {int(desk.group(1))}"
    if re.search(r"\d", value):
        return "Участник"
    words = [w for w in value.replace(".", " ").split() if w]
    if not words or any(re.search(r"[A-Za-z]", w) and re.search(r"[А-Яа-яЁё]", w) for w in words):
        return "Участник"   # смесь латиницы и кириллицы в одном слове — не имя, а попытка обхода
    if len(words) >= 3:
        first, initial = words[1], words[0]
    elif len(words) == 2:
        first, initial = words[0], words[1]
        if len(words[0]) == 1 and len(words[1]) > 1:          # «И. Петров» → «Петров И.» не имя; берём слово
            first, initial = words[1], words[0]
    else:
        first, initial = words[0], ""
    first = "-".join(_cap(part) for part in first.lower().split("-"))[: max(1, limit - 3)]
    alias = f"{first} {initial[0].upper()}." if initial else first
    return alias[:limit]
