def subject_key(task_context: str, query: str = "") -> str:
    """Группа предмета: сначала по названию задания, потом по вопросу ученика; иначе general."""
    for text in (task_context, query):
        t = (text or "").lower()
        if not t:
            continue
        for tier in _TIERS:
            for key, stems in tier:
                if any(stem in t for stem in stems):
                    return key
    return "general"


def guide_for(task_context: str, query: str = "") -> Guide:
    """Копия шаблона (вызывающий код может безопасно менять результат)."""
    g = GUIDES[subject_key(task_context, query)]
    return {"subject": g["subject"], "title": g["title"], "steps": list(g["steps"])}
