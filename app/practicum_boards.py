def _items(raw: list[tuple[str, str, str]], prefix: str) -> list[dict[str, str]]:
    return [{"id": f"{prefix}{i}", "text": text, "bucket": bucket, "why": why} for i, (text, bucket, why) in enumerate(raw, 1)]


def board(buckets: list[tuple[str, str]], raw: list[tuple[str, str, str]], prefix: str) -> dict[str, Any]:
    """Доска классификатора: ``raw`` — (текст карточки, id группы, почему она там)."""
    return L("classify", {"assign": {}}, buckets=[{"id": b, "title": t} for b, t in buckets], items=_items(raw, prefix))


def chain(raw: list[tuple[str, str]], prefix: str, seed: str) -> dict[str, Any]:
    """Цепочка: ``raw`` в верном порядке — (текст, почему здесь); на старте карточки перемешаны детерминированно."""
    items = [{"id": f"{prefix}{i}", "text": text, "why": why} for i, (text, why) in enumerate(raw, 1)]
    correct = [i["id"] for i in items]
    shuffled = correct[:]
    rng = random.Random(int.from_bytes(hashlib.sha256(seed.encode()).digest()[:8], "big"))
    for _ in range(20):
        rng.shuffle(shuffled)
        if shuffled != correct:
            break
    return L("order", {"order": shuffled}, items=items, correct=correct)


def field(w: int, h: int, start: tuple[int, int], goal: tuple[int, int], walls: list[tuple[int, int]] | None = None,
          max_len: int | None = None) -> dict[str, Any]:
    return L("robot", {"program": []}, w=w, h=h, start=list(start), goal=list(goal), walls=[list(x) for x in walls or []], max_len=max_len)


def _len_rule(limit: int) -> dict[str, Any]:
    return c("length", "le", limit, f"Программа длиннее {limit} команд — используй циклы «повтори n раз».", "loops")


def B(pid: str, topic_id: str, title: str, goal: str, summary_: str, difficulty: str, minutes: int, fmt: str, mechanic: str,
      model: str, stages: list[dict[str, Any]], quiz: list[dict[str, Any]] | None = None) -> None:
    BOARDS.append(P(pid, topic_id, title, goal, summary_, difficulty, minutes, fmt, mechanic, model, stages, quiz))


def cls_stage(kind: str, task: str, lab: dict[str, Any], skill: int, hints: list[str] | None = None) -> dict[str, Any]:
    cons = [_ALL_ASSIGNED, _CORRECT]
    if kind == "exploration":
        return explore(task, lab, cons, "Каждая карточка показывает, почему она в этой группе, — читай пояснения после проверки.", skill)
    if kind == "action_check":
        return act(task, lab, cons, [], hints or [], skill)
    if kind == "progressive_hints":
        return hinted(task, lab, cons, [], hints or [], skill)
    return final(task, lab, cons, [], skill)


def ord_stage(kind: str, task: str, lab: dict[str, Any], skill: int, hints: list[str] | None = None) -> dict[str, Any]:
    cons = [_ORDER_DONE, _ORDER_OK]
    if kind == "exploration":
        return explore(task, lab, cons, "Порядок проверяется по каждой паре соседних карточек.", skill)
    if kind == "action_check":
        return act(task, lab, cons, [], hints or [], skill)
    if kind == "progressive_hints":
        return hinted(task, lab, cons, [], hints or [], skill)
    return final(task, lab, cons, [], skill)


