def rob_stage(kind: str, task: str, lab: dict[str, Any], extra: list[dict[str, Any]], skill: int, hints: list[str] | None = None) -> dict[str, Any]:
    cons = [_REACHED, _GOAL, *extra]
    if kind == "exploration":
        return explore(task, lab, cons, "Программа выполняется по шагам: следи за путём Робота на поле.", skill)
    if kind == "action_check":
        return act(task, lab, cons, [], hints or [], skill)
    if kind == "progressive_hints":
        return hinted(task, lab, cons, [], hints or [], skill)
    return final(task, lab, cons, [], skill)


