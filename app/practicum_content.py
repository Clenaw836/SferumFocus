# ------------------------------------------------------------------------------------ строители
def c(q: str, op: str, v: Any = None, say: str = "", principle: str = "model", tol: float = 1e-6) -> dict[str, Any]:
    """Ограничение на состояние модели."""
    return {"q": q, "op": op, "v": v, "say": say, "principle": principle, "tol": tol}


def ans(field: str, label: str, say: str, q: str | None = None, v: Any = None, tol: float = 0.01,
        principle: str = "answer") -> dict[str, Any]:
    """Поле ответа ученика: сверяется с величиной ``q`` его модели или с числом ``v``."""
    out: dict[str, Any] = {"field": field, "label": label, "say": say, "tol": tol, "principle": principle}
    if q is not None:
        out["q"] = q
    else:
        out["v"] = v
    return out


def intro(body: str, life: str, exam: str) -> dict[str, Any]:
    return {"kind": "intro", "body": body, "real_life": life, "exam": exam}


def warm(question: str, options: list[str], correct: int, explain: str, skill: int, body: str = "") -> dict[str, Any]:
    return {"kind": "warmup", "body": body,
            "question": {"text": question, "options": options, "correct": correct, "explain": explain}, "skill": skill}


def explore(task: str, lab: dict[str, Any], cons: list[dict[str, Any]], observe: str, skill: int,
            answers: list[dict[str, Any]] | None = None) -> dict[str, Any]:
    return {"kind": "exploration", "task": task, "lab": lab, "constraints": cons, "answers": answers or [],
            "observe": observe, "skill": skill,
            "hints": ["Меняй по одному параметру и смотри, что происходит на холсте.",
                      "Сравни показания модели до и после изменения.",
                      "Сверь своё состояние с формулировкой задания: какое условие ещё не выполнено?"]}


def act(task: str, lab: dict[str, Any], cons: list[dict[str, Any]], answers: list[dict[str, Any]], hints: list[str],
        skill: int) -> dict[str, Any]:
    assert len(hints) == 3
    return {"kind": "action_check", "task": task, "lab": lab, "constraints": cons, "answers": answers,
            "hints": hints, "skill": skill}


def hinted(task: str, lab: dict[str, Any], cons: list[dict[str, Any]], answers: list[dict[str, Any]], hints: list[str],
           skill: int) -> dict[str, Any]:
    assert len(hints) == 3
    return {"kind": "progressive_hints", "task": task, "lab": lab, "constraints": cons, "answers": answers,
            "hints": hints, "skill": skill}


def err(case: str, question: str, options: list[str], correct: int, explain: str, skill: int,
        lab: dict[str, Any] | None = None) -> dict[str, Any]:
    return {"kind": "error_explanation", "case": case, "lab": lab or {},
            "question": {"text": question, "options": options, "correct": correct, "explain": explain}, "skill": skill}


def final(task: str, lab: dict[str, Any], cons: list[dict[str, Any]], answers: list[dict[str, Any]], skill: int) -> dict[str, Any]:
    return {"kind": "final_challenge", "task": task, "lab": lab, "constraints": cons, "answers": answers, "skill": skill}


def summary(learned: list[str], next_step: str) -> dict[str, Any]:
    return {"kind": "summary_and_next", "learned": learned, "next_step": next_step}


def q_single(text: str, options: list[str], correct: int, explain: str, skill: int) -> dict[str, Any]:
    return {"kind": "single_choice", "text": text, "options": options, "correct": correct, "explain": explain, "skill": skill}


def q_short(text: str, value: float | None, explain: str, skill: int, tol: float = 0.01, answers: list[str] | None = None) -> dict[str, Any]:
    return {"kind": "short_answer", "text": text, "value": value, "answers": answers or [], "tol": tol,
            "explain": explain, "skill": skill}


def q_match(text: str, pairs: list[tuple[str, str]], explain: str, skill: int) -> dict[str, Any]:
    return {"kind": "matching", "text": text, "pairs": [list(p) for p in pairs], "explain": explain, "skill": skill}


def q_order(text: str, items: list[str], explain: str, skill: int) -> dict[str, Any]:
    return {"kind": "ordering", "text": text, "items": items, "explain": explain, "skill": skill}


def q_diagram(text: str, model: str, state: dict[str, Any], options: list[str], correct: int, explain: str,
              skill: int) -> dict[str, Any]:
    return {"kind": "diagram_question", "text": text, "diagram": {"model": model, "state": state},
            "options": options, "correct": correct, "explain": explain, "skill": skill}


def P(pid: str, topic_id: str, title: str, goal: str, summary_: str, difficulty: str, minutes: int, fmt: str,
      mechanic: str, model: str, stages: list[dict[str, Any]], quiz: list[dict[str, Any]] | None = None,
      principles: dict[str, str] | None = None) -> dict[str, Any]:
    assert difficulty in DIFFICULTY_RU and fmt in FORMAT_TYPES, pid
    kinds = tuple(s["kind"] for s in stages)
    assert kinds == STAGE_KINDS, (pid, kinds)
    return {"practicum_id": pid, "topic_id": topic_id, "title": title, "learning_goal": goal, "summary": summary_,
            "difficulty": difficulty, "duration_minutes": minutes, "format_type": fmt, "mechanic_kind": mechanic,
            "model": model, "stages": stages, "quiz": quiz or [], "principles": principles or {}, "version": 1,
            # v3.2: честный флаг вместо «verified_by_admin» — этап за этапом проходит автоматическую проверку
            # решаемости и согласованности ответов (tests/test_practicum_content.py). Рецензии методиста не было.
            "auto_verified_solvable": True}


def L(model: str, initial: dict[str, Any], **config: Any) -> dict[str, Any]:
    """Конфигурация лаборатории этапа: модель, стартовое состояние, параметры (x_true, t0, сетка…)."""
    return {"model": model, "initial": initial, **config}


