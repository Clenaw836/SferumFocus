export const topicByKey = (k: string) => TOPICS.find((t) => t.key === k);
export const topicFor = (title: string) => TOPICS.find((t) => t.re.test(title));

export interface RoundQ { q: string; options: string[]; answer: number; why: string;
  /** v3.2.1 · откуда вопрос: повтор ошибки, генератор (новые числа) или банк. */
  src?: "review" | "gen" | "bank" }

/** 5 вопросов: перемешаны и вопросы, и варианты. rnd — для детерминированных тестов. */
export function makeRound(topic: Topic, n = 5, rnd: () => number = Math.random): RoundQ[] {
  const shuffle = <T,>(xs: T[]) => { const a = [...xs]; for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(rnd() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; } return a; };
  return shuffle(topic.qs).slice(0, n).map((x) => {
    const order = shuffle([0, 1, 2, 3]);
    return { q: x.q, options: order.map((k) => x.a[k]), answer: order.indexOf(0), why: x.why };
  });
}

/**
 * Очки: 100 за верный + до 50 за скорость. Максимум раунда — 750 (не менялся).
 * v16.1: лимит на ответ — QUIZ_CONFIG.questionSeconds (20 с), а окно бонуса за скорость осталось прежним — 15 с,
 * поэтому за тот же ответ очков столько же, как в v16.0, и рекорды сопоставимы. Пропуск по времени — 0.
 */
export const QSEC = QUIZ_CONFIG.questionSeconds;
const SPEED_MS = QUIZ_CONFIG.speedWindowSeconds * 1000;
export const pointsFor = (ok: boolean, ms: number) => (ok ? 100 + Math.round(50 * Math.max(0, 1 - ms / SPEED_MS)) : 0);
export const ROUND_MAX = 5 * 150;

export interface Challenge { key: string; score: number }
/** startapp=blitz_lit_540 → вызов; всё остальное → null (диплинк — недоверенный ввод). */
export function parseChallenge(sp: string): Challenge | null {
  const m = /^blitz_([a-z]{2,6})_(\d{1,3})$/.exec(sp);
  if (!m || !topicByKey(m[1])) return null;
  const score = Number(m[2]);
  return score > 0 && score <= ROUND_MAX ? { key: m[1], score } : null;
}
