/** Группа предмета: сначала по названию задания, потом по вопросу ученика; иначе general. */
export function subjectKey(taskContext: string, query = ""): GuideKey {
  for (const text of [taskContext, query]) {
    const t = (text || "").toLowerCase();
    if (!t) continue;
    for (const tier of TIERS) for (const [key, stems] of tier) if (stems.some((s) => t.includes(s))) return key;
  }
  return "general";
}

/** Копия шаблона (вызывающий код может безопасно менять результат). */
export function socraticGuide(taskContext: string, query = ""): SocraticGuide {
  const g = GUIDES[subjectKey(taskContext, query)];
  return { subject: g.subject, title: g.title, steps: [...g.steps] };
}
